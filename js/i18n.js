    textNodes.forEach(function (item) {
      item.node.nodeValue = isChinese && Object.prototype.hasOwnProperty.call(zh, item.key)
        ? preserveWhitespace(item.original, zh[item.key])
        : item.original;
    });
    document.querySelectorAll('[data-nav-en]').forEach(function (label) {
      label.textContent = isChinese ? (label.getAttribute('data-nav-zh') || label.getAttribute('data-nav-en') || '') : (label.getAttribute('data-nav-en') || '');
    });
    attrNodes.forEach(function (item) {
      var next = isChinese ? zh[item.original] : null;
      if (next) item.el.setAttribute('aria-label', next);
      else item.el.setAttribute('aria-label', item.original);
    });
